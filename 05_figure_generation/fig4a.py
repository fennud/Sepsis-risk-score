# 8. Exact organ-label permutation / Mantel-type test
# =========================================================
def exact_matrix_permutation_test(
    x_matrix,
    y_matrix,
    organ_order
):
    """
    Exact label permutation of one symmetric organ-by-organ matrix.

    With five organs there are exactly 5! = 120 permutations.
    For each permutation, both rows and columns of y_matrix are relabeled
    together, preserving its internal matrix structure.
    """
    x = upper_triangle_values(
        x_matrix,
        organ_order
    )

    y = upper_triangle_values(
        y_matrix,
        organ_order
    )

    ok = (
        np.isfinite(x)
        &
        np.isfinite(y)
    )

    x_obs = x[ok]
    y_obs = y[ok]

    if len(x_obs) < 3:
        raise ValueError(
            "有效器官对不足，无法进行矩阵相关。"
        )

    r_obs, _ = pearsonr(
        x_obs,
        y_obs
    )

    perm_rs = []

    for perm in permutations(
        organ_order
    ):
        perm = list(
            perm
        )

        # Relabel y matrix by the same permutation on rows and columns.
        y_perm_mat = y_matrix.loc[
            perm,
            perm
        ].copy()

        # Rename permuted labels back to the original positional labels,
        # so upper-triangle cells are compared position-by-position.
        y_perm_mat.index = organ_order
        y_perm_mat.columns = organ_order

        yp = upper_triangle_values(
            y_perm_mat,
            organ_order
        )

        okp = (
            np.isfinite(x)
            &
            np.isfinite(yp)
        )

        if okp.sum() < 3:
            continue

        rp, _ = pearsonr(
            x[okp],
            yp[okp]
        )

        perm_rs.append(
            rp
        )

    perm_rs = np.asarray(
        perm_rs,
        dtype=float
    )

    # Exact two-sided P, including the observed labeling among all 120.
    p_exact = (
        np.sum(
            np.abs(
                perm_rs
            )
            >=
            abs(
                r_obs
            )
        )
        /
        len(
            perm_rs
        )
    )

    return {
        "r": r_obs,
        "R2": r_obs ** 2,
        "P_exact": p_exact,
        "n_pairs": len(x_obs),
        "n_label_permutations": len(perm_rs),
        "perm_r": perm_rs,
    }


