# 5. Chronic susceptibility similarity
# =========================================================
def compute_chronic_susceptibility_similarity(beta_mat):
    """
    Similarity between two organs = Pearson correlation between their
    seven age/sex-adjusted chronic-disease log-OR coefficients.
    """
    similarity = beta_mat[
        ORGAN_ORDER
    ].corr(
        method="pearson",
        min_periods=5
    )

    return similarity


