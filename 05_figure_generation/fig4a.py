def ensure_cols(df, cols, desc):
    missing = [
        c for c in cols
        if c not in df.columns
    ]

    if missing:
        raise ValueError(
            f"{desc} 缺少以下字段：{missing}"
        )


def to_binary_preserve_na(series):
    """
    Convert observed values to 0/1 while preserving missingness.
    """
    s = pd.to_numeric(
        series,
        errors="coerce"
    )

    out = pd.Series(
        np.nan,
        index=s.index,
        dtype=float
    )

    mask = s.notna()

    out.loc[mask] = (
        s.loc[mask] > 0
    ).astype(float)

    return out


def fisher_z(r):
    if pd.isna(r):
        return np.nan

    r = np.clip(
        float(r),
        -0.999999,
        0.999999
    )

    return np.arctanh(r)


def upper_triangle_values(mat, organ_order):
    vals = []

    for i in range(
        len(organ_order)
    ):
        for j in range(
            i + 1,
            len(organ_order)
        ):
            vals.append(
                mat.loc[
                    organ_order[i],
                    organ_order[j]
                ]
            )

    return np.asarray(
        vals,
        dtype=float
    )


