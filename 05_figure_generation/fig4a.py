"""
Chronic-disease susceptibility similarity -> organ-specific loading similarity

Current analysis framework
--------------------------
Cohort:
    MIMIC-IV current formal_v2 pipeline.

Predictor / baseline window:
    0–6 h after sepsis onset.

Organ outcomes:
    24–48 h organ failure for five organs:
    Respiratory, Coagulation, Liver, Cardiovascular, Renal.

Purpose
-------
1) Estimate, among patients with >=1 chronic disease in the DISCOVERY cohort,
   each organ's chronic-disease susceptibility profile using age/sex-adjusted
   multivariable logistic regression.

   For organ j:
       logit P(Y_j,24-48h = 1)
       = alpha
         + beta_HTN * HTN
         + beta_DM * DM
         + beta_CHF * CHF
         + beta_Cancer * Cancer
         + beta_COPD/RLD * COPD/RLD
         + beta_CKD * CKD
         + beta_CLD * CLD
         + age
         + sex

   The 7 chronic-disease coefficients form a susceptibility vector V_j.

2) For each pair of organs, calculate chronic-disease susceptibility similarity:
       corr(V_i, V_j)
   using Pearson correlation across the seven chronic-disease coefficients.

3) Read the current Fig5a feature-loading matrix and calculate loading similarity
   between organ-specific models, separately for:
       - No chronic history models
       - Any chronic history models

4) Test whether organ pairs with more similar chronic-disease susceptibility
   profiles also have more similar model loading profiles.

   Primary scatter plots and permutation tests both use raw Pearson r for
   loading similarity (no Fisher-z transformation), so plotted values, R²,
   axis labels and P values are directly consistent.

   Because both matrices are symmetric and there are only five organs,
   the primary permutation test is an exact organ-label permutation:
       5! = 120 permutations.
   This preserves the dependence structure among the 10 unique organ pairs.

Important interpretation
------------------------
This is an association / structural-similarity analysis.
It does NOT establish that chronic disease causes the model-loading similarity.
"""

