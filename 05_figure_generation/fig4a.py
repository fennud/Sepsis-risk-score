def build_pair_table(
    chronic_similarity,
    loading_similarity_no,
    loading_similarity_any
):
    rows = []

    for i in range(
        len(ORGAN_ORDER)
    ):
        for j in range(
            i + 1,
            len(ORGAN_ORDER)
        ):
            organ1 = ORGAN_ORDER[i]
            organ2 = ORGAN_ORDER[j]

            chronic_r = chronic_similarity.loc[
                organ1,
                organ2
            ]

            load_r_no = loading_similarity_no.loc[
                organ1,
                organ2
            ]

            load_r_any = loading_similarity_any.loc[
                organ1,
                organ2
            ]

            rows.append({
                "pair":
                    f"{organ1}-{organ2}",
                "organ1":
                    organ1,
                "organ2":
                    organ2,
                "chronic_susceptibility_similarity_r":
                    chronic_r,
                "loading_similarity_no_chronic_r":
                    load_r_no,
                "loading_similarity_any_chronic_r":
                    load_r_any,
                "loading_similarity_no_chronic_fisher_z":
                    fisher_z(
                        load_r_no
                    ),
                "loading_similarity_any_chronic_fisher_z":
                    fisher_z(
                        load_r_any
                    ),
            })

    return pd.DataFrame(
        rows
    )


