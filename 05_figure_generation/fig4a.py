# 4. Estimate organ-specific chronic-disease susceptibility
# =========================================================
def fit_chronic_susceptibility_profiles(df_chronic):
    """
    For each organ, fit:

        organ failure at 24–48 h
        ~ 7 chronic disease flags + age + sex

    The seven chronic-disease log-odds coefficients are retained as the
    organ's chronic-disease susceptibility vector.
    """
    beta_mat = pd.DataFrame(
        np.nan,
        index=CHRONIC_FLAGS,
        columns=ORGAN_ORDER,
        dtype=float
    )

    or_mat = pd.DataFrame(
        np.nan,
        index=CHRONIC_FLAGS,
        columns=ORGAN_ORDER,
        dtype=float
    )

    summary_rows = []

    model_covars = (
        CHRONIC_FLAGS
        +
        [
            "age10",
            "sex_male",
        ]
    )

    for organ in ORGAN_ORDER:
        outcome_col = ORGAN_OUTCOME_COLS[
            organ
        ]

        dat = df_chronic[
            [outcome_col]
            +
            model_covars
        ].dropna().copy()

        y = dat[
            outcome_col
        ].astype(int)

        if y.nunique() < 2:
            raise ValueError(
                f"{organ}: 24–48 h outcome 缺少正/负两类，无法拟合 logistic regression。"
            )

        X = dat[
            model_covars
        ].astype(float)

        # Remove any zero-variance nuisance covariate.
        # Chronic flags are intentionally retained whenever they vary.
        zero_var = [
            c for c in X.columns
            if X[c].nunique(
                dropna=True
            ) < 2
        ]

        if zero_var:
            print(
                f"WARNING [{organ}] zero-variance covariates dropped: "
                f"{zero_var}"
            )

            X = X.drop(
                columns=zero_var
            )

        X = sm.add_constant(
            X,
            has_constant="add"
        )

        try:
            model = sm.GLM(
                y,
                X,
                family=sm.families.Binomial()
            )

            result = model.fit(
                maxiter=200,
                disp=False
            )

        except Exception as e:
            raise RuntimeError(
                f"{organ} logistic model failed: {e}"
            )

        n_total = len(dat)
        n_event = int(
            (y == 1).sum()
        )
        n_nonevent = int(
            (y == 0).sum()
        )

        print(
            f"{organ}: "
            f"n={n_total:,}, "
            f"failure={n_event:,}, "
            f"non-failure={n_nonevent:,}"
        )

        for chronic_col in CHRONIC_FLAGS:
            if chronic_col not in result.params.index:
                beta = np.nan
                se = np.nan
                pval = np.nan
                ci_low = np.nan
                ci_high = np.nan

            else:
                beta = float(
                    result.params[
                        chronic_col
                    ]
                )

                se = float(
                    result.bse[
                        chronic_col
                    ]
                )

                pval = float(
                    result.pvalues[
                        chronic_col
                    ]
                )

                ci = result.conf_int().loc[
                    chronic_col
                ]

                ci_low = float(
                    ci.iloc[0]
                )

                ci_high = float(
                    ci.iloc[1]
                )

            beta_mat.loc[
                chronic_col,
                organ
            ] = beta

            or_mat.loc[
                chronic_col,
                organ
            ] = (
                np.exp(beta)
                if pd.notna(beta)
                else np.nan
            )

            summary_rows.append({
                "organ": organ,
                "outcome": outcome_col,
                "chronic_disease": chronic_col,
                "chronic_label": CHRONIC_LABELS[chronic_col],
                "beta_logOR": beta,
                "OR": (
                    np.exp(beta)
                    if pd.notna(beta)
                    else np.nan
                ),
                "OR_CI_low": (
                    np.exp(ci_low)
                    if pd.notna(ci_low)
                    else np.nan
                ),
                "OR_CI_high": (
                    np.exp(ci_high)
                    if pd.notna(ci_high)
                    else np.nan
                ),
                "SE": se,
                "P": pval,
                "n": n_total,
                "n_failure": n_event,
                "n_nonfailure": n_nonevent,
            })

    summary_df = pd.DataFrame(
        summary_rows
    )

    return (
        beta_mat,
        or_mat,
        summary_df
    )


